const fallbackMonths: SemesterTopic['month'][]=['Сентябрь','Октябрь','Ноябрь','Ноябрь','Декабрь','Январь','Январь','Февраль']

export function semesterPlan(subject:Subject):SemesterTopic[]{
  const plan=plans[subject.id]
  if(plan) return plan
  const existing=subject.lessons.map((lesson,index)=>m(lesson.title.replace(/^Тема\s*\d+\.\s*/i,''),fallbackMonths[index]||'Январь',lesson.goal))
  while(existing.length<8){
    const n=existing.length+1
    existing.push(m(`Тема ${n}. Углубление и практикум`,fallbackMonths[existing.length]||'Февраль',`Углубить ключевые идеи курса «${subject.title}» и применить их в самостоятельной работе.`))
  }
  return existing.slice(0,8)
}
